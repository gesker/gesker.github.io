#!/usr/bin/env python3
"""Audit every built page for a consistent look and feel.

Static checks on the generated HTML -- no browser needed. For each page it
reports the pieces that make the site look like one site:

    one h2 title, card treatment, chipped logos, the related/cross-link line,
    the site footer, the same stylesheet count, no legacy floated images, no
    literal {{#include}} or stray markdown that failed to render

Usage:
    python3 scripts/check_pages.py [--dir result] [--json]

Exit code is 1 when a page breaks an invariant.
"""

import json
import os
import re
import sys

# Generated by mdbook itself, or not part of the browsable site
IGNORE = {"print.html", "404.html", "toc.html"}
IGNORE_SUFFIX = ("_for_pdf_only.html",)


def audit(path):
    html = open(path, encoding="utf-8", errors="replace").read()
    name = os.path.basename(path)
    body = html.split("<main>", 1)[-1].split("</main>", 1)[0] if "<main>" in html else html

    def count(pattern):
        return len(re.findall(pattern, body))

    cards = count(r'class="info-card"')
    grids = count(r'class="info-grid')
    grid_items = count(r'<li[^>]*>')
    imgs = re.findall(r"<img[^>]*>", body)
    imgs_total = len(imgs)
    imgs_chipped = sum(1 for i in imgs if "info-logo" in i or "hero-avatar" in i)
    legacy_float = sum(1 for i in imgs if "float:" in i)
    bare_img_in_card = sum(
        1 for i in re.findall(r'<div class="info-card">.*?</div>', body, re.S) for _ in [0]
        if "<img" in i and "info-logo" not in i
    )
    return {
        "page": name,
        "h2": count(r"<h2"),
        "h3": count(r"<h3"),
        "h4": count(r"<h4"),
        "h1": count(r"<h1"),
        "cards": cards,
        "grids": grids,
        "grid_items": grid_items,
        "imgs": imgs_total,
        "chipped": imgs_chipped,
        "legacy_float": legacy_float,
        "bare_img_in_card": bare_img_in_card,
        "hr": count(r"<hr>"),
        "related": 1 if 'class="related"' in body else 0,
        "chips": 1 if 'class="toc-chips"' in body else 0,
        "footer": 1 if 'class="site-footer"' in html else 0,
        "hero": 1 if 'class="hero' in body else 0,
        "sheets": len(re.findall(r'rel="stylesheet"', html)),
        "raw_include": 1 if "{{#include" in html else 0,
        # redirect stubs and the printable document are not browsable pages
        "stub": 1 if 'http-equiv="refresh"' in html else 0,
        "document": 1 if name in ("resume_full.html", "resume_ats.html") else 0,
        "h1": count(r"<h1"),
        "code_blocks": count(r"<pre"),
        "tables": count(r"<table"),
        "chars": len(re.sub(r"<[^>]+>", " ", body)),
    }


def main(argv):
    root = "result"
    if "--dir" in argv:
        root = argv[argv.index("--dir") + 1]
    rows = []
    for name in sorted(os.listdir(root)):
        if not name.endswith(".html") or name in IGNORE or name.endswith(IGNORE_SUFFIX):
            continue
        rows.append(audit(os.path.join(root, name)))

    problems = []
    for r in rows:
        if r["raw_include"]:
            problems.append(f"{r['page']}: literal {{{{#include}}}} -- an include failed to render")
        if r["legacy_float"]:
            problems.append(f"{r['page']}: {r['legacy_float']} image(s) still use an inline float")
        if r["bare_img_in_card"]:
            problems.append(f"{r['page']}: {r['bare_img_in_card']} card image(s) without the logo chip class")
        if r["imgs"] and r["chipped"] < r["imgs"]:
            problems.append(f"{r['page']}: {r['imgs'] - r['chipped']} image(s) outside the chip system")
        if r["stub"] or r["document"]:
            continue
        if r["h1"] != 1:
            problems.append(f"{r['page']}: {r['h1']} h1 page titles, expected exactly 1")
        if r["h2"] == 0 and r["cards"] == 0 and r["grids"] == 0:
            problems.append(f"{r['page']}: no section headings and no cards -- empty-feeling page")
        if not r["footer"]:
            problems.append(f"{r['page']}: no site footer")
        # a hero plus chips IS a treatment: the hub page is hero-led by design
        if r["chars"] > 400 and not (
            r["cards"]
            or r["grids"]
            or r["tables"]
            or r["code_blocks"]
            or r["hero"]
            or r["chips"]
        ):
            problems.append(f"{r['page']}: {r['chars']} chars of content with no card/grid/table treatment")
        if r["chars"] > 400 and not (r["related"] or r["chips"]):
            problems.append(f"{r['page']}: no related line or section chips -- no way to click onward")

    if "--json" in argv:
        print(json.dumps({"pages": rows, "problems": problems}, indent=1))
        return 1 if problems else 0

    hdr = f"{'page':30} {'h2':>2} {'h3':>2} {'cards':>5} {'grid':>4} {'imgs':>4} {'chip':>4} {'hr':>2} {'rel':>3} {'chips':>5} {'ftr':>3} {'css':>3} {'chars':>5}"
    print(hdr)
    for r in rows:
        print(
            f"{r['page'][:30]:30} {r['h2']:>2} {r['h3']:>2} {r['cards']:>5} {r['grids']:>4} "
            f"{r['imgs']:>4} {r['chipped']:>4} {r['hr']:>2} {r['related']:>3} {r['chips']:>5} "
            f"{r['footer']:>3} {r['sheets']:>3} {r['chars']:>5}"
        )
    print()
    if problems:
        print(f"{len(problems)} inconsistency(ies):")
        for line in problems:
            print("  " + line)
    else:
        print(f"{len(rows)} pages, one consistent look")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
